import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const manifest=JSON.parse(fs.readFileSync(new URL('../plugins/napcat/plugin.json',import.meta.url),'utf8'));
const root={children:[],append(value){this.children.push(value);},replaceChildren(){this.children=[];}};
const create=(parent,label,value,change,options)=>{const input={label,value,checked:Boolean(value),disabled:false,change,options};parent.append(input);return input;};
const context=vm.createContext({el:(_tag,_class,text)=>({text}),field:create,toggle:create});
vm.runInContext(fs.readFileSync(new URL('../ui/plugin-forms.js',import.meta.url),'utf8'),context);
context.manifest=manifest;context.root=root;context.configuration={stricterSecurity:false,isolateMemory:false,allowDesktopControl:true,controlTrust:'allowed',reviewReplies:false};
vm.runInContext('renderDeclaredPluginSettings(root,manifest,configuration)',context);
const input=key=>root.children.find(v=>v.label===manifest.settings_ui.find(spec=>spec.key===key).label);
assert.equal(input('isolateMemory').checked,false);
input('stricterSecurity').change(true);
for(const key of ['isolateMemory','allowDesktopControl','controlTrust','reviewReplies'])assert.equal(input(key).disabled,true,key);
assert.equal(input('isolateMemory').checked,true);
assert.equal(input('allowDesktopControl').checked,false);
assert.equal(input('controlTrust').value,'owner');
assert.equal(input('reviewReplies').checked,true);
assert.equal(context.configuration.controlTrust,'allowed','preset preserves independent choices');
input('stricterSecurity').change(false);
assert.equal(input('controlTrust').disabled,false);
assert.equal(input('controlTrust').value,'allowed');
assert.equal(input('reviewReplies').checked,false);
assert.equal(input('allowDesktopControl').checked,true);
console.log('PASS NapCat security preset controls, effective values, locking and restoration');
